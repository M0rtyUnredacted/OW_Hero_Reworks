#!/usr/bin/env node
// Regenerates docs/api/*.md from OverPy's Workshop data tables.
// Run after bumping the OverPy commit in tools/setup.sh:
//   tools/setup.sh && node tools/gen-api-docs.js
//
// These files are the source of truth for exact English names, argument
// order and enum values. Grep them before using any action or value.

"use strict";
const fs = require("fs");
const path = require("path");
const { execSync } = require("child_process");

const ROOT = path.resolve(__dirname, "..");
const OVERPY_DIR = path.join(ROOT, ".tools/overpy");
const OVERPY = path.join(OVERPY_DIR, "out/overpy_standalone.js");
const OUT = path.join(ROOT, "docs/api");

if (!fs.existsSync(OVERPY)) {
    console.error("OverPy is not built. Run: tools/setup.sh");
    process.exit(2);
}

const en = (x) => (x && typeof x === "object" ? x["en-US"] : x) ?? "";
const oneLine = (s) => String(s || "").replace(/\s+/g, " ").trim();

function typeStr(t) {
    if (t == null) return "";
    if (typeof t === "string") return t;
    if (Array.isArray(t)) return t.map(typeStr).join(" | ");
    if (t.Array) return `Array<${typeStr(t.Array)}>`;
    return Object.entries(t).map(([k, v]) => `${k}<${typeStr(v)}>`).join(" | ");
}

function defaultStr(d) {
    if (d === undefined) return "";
    return ` = ${typeof d === "string" ? d.replace(/_/g, " ").toLowerCase().replace(/\b\w/g, (c) => c.toUpperCase()) : d}`;
}

function header(title, blurb, rev) {
    return `# ${title}\n\n> Generated by \`tools/gen-api-docs.js\` from [OverPy](https://github.com/Zezombye/overpy) @ \`${rev.slice(0, 12)}\`. Do not edit by hand.\n> ${blurb}\n\n`;
}

// Functions shared by actions and values. Workshop syntax is `Name(arg, arg)`.
function renderFuncs(table, kind) {
    const rows = Object.entries(table)
        .filter(([, f]) => en(f))
        .sort((a, b) => en(a[1]).localeCompare(en(b[1])));
    let toc = "";
    let body = "";
    for (const [key, f] of rows) {
        const name = en(f);
        const args = f.args || [];
        const sig = args.length ? `${name}(${args.map((a) => en(a.nameLocalized) || a.name).join(", ")})` : name;
        toc += `- ${name}\n`;
        body += `### ${name}\n\n\`${sig}\``;
        if (kind === "value" && f.return) body += ` → \`${typeStr(f.return)}\``;
        body += `  \n_OverPy:_ \`${key}\`\n\n${oneLine(en(f.description))}\n\n`;
        if (args.length) {
            body += "| # | Argument | Type | Description |\n|---|---|---|---|\n";
            args.forEach((a, i) => {
                body += `| ${i + 1} | ${en(a.nameLocalized) || a.name}${defaultStr(a.default)} | \`${typeStr(a.type).replace(/\|/g, "\\|")}\` | ${oneLine(en(a.description)).replace(/\|/g, "\\|")} |\n`;
            });
            body += "\n";
        }
    }
    return { count: rows.length, text: `## Index\n\n${toc}\n## Reference\n\n${body}` };
}

(async () => {
    const op = require(OVERPY);
    await op.readyPromise;
    let rev = "unknown";
    try {
        rev = execSync("git rev-parse HEAD", { cwd: OVERPY_DIR }).toString().trim();
    } catch {}

    fs.mkdirSync(OUT, { recursive: true });

    const actions = renderFuncs(op.actionKw, "action");
    fs.writeFileSync(
        path.join(OUT, "actions.md"),
        header("Workshop Actions", `${actions.count} actions. Each is a statement ending in \`;\` inside \`actions { }\`.`, rev) + actions.text,
    );

    const values = renderFuncs(op.valueFuncKw, "value");
    fs.writeFileSync(
        path.join(OUT, "values.md"),
        header("Workshop Values", `${values.count} values. Values with no arguments are written bare (e.g. \`Event Player\`, \`Victim\`).`, rev) + values.text,
    );

    // Enums: the Workshop writes these bare (e.g. `Ignore Condition`) or via a
    // wrapper value (e.g. `Color(Aqua)`, `Button(Ability 1)`, `Hero(Symmetra)`).
    let c = "";
    const enums = Object.entries(op.constantValues)
        .filter(([k]) => !k.startsWith("__") && !["HeroLiteral", "MapLiteral", "GamemodeLiteral"].includes(k))
        .sort((a, b) => a[0].localeCompare(b[0]));
    for (const [enumName, members] of enums) {
        const names = Object.entries(members)
            .filter(([k, m]) => k !== "description" && m && en(m) && !m.onlyInOverpy && !m.onlyInOw1)
            .map(([, m]) => en(m));
        if (!names.length) continue;
        c += `## ${enumName}\n\n${oneLine(en(members.description))}\n\n${names.map((n) => `\`${n}\``).join(" · ")}\n\n`;
    }
    fs.writeFileSync(
        path.join(OUT, "constants.md"),
        header("Workshop Enum Constants", "Names under each heading are the exact in-game spellings. `ButtonLiteral` is used as `Button(X)`, `ColorLiteral` as `Color(X)`, `TeamLiteral` as `Team(X)`.", rev) + c,
    );

    // Heroes: in-game name (used as `Hero(X)` and in event hero slots) and ability names.
    let h = "| Hero | Ability 1 (Shift) | Ability 2 (E) | Ultimate (Q) |\n|---|---|---|---|\n";
    for (const hero of Object.values(op.heroKw).sort((a, b) => en(a).localeCompare(en(b)))) {
        h += `| ${en(hero)} | ${en(hero.ability1)} | ${en(hero.ability2)} | ${en(hero.ultimate)} |\n`;
    }
    h += "\n## Events\n\nExact names for the first line of a rule's `event { }` block.\n\n";
    for (const [k, e] of Object.entries(op.eventKw)) {
        if (!k.startsWith("__") && en(e)) h += `- \`${en(e)}\`\n`;
    }
    fs.writeFileSync(
        path.join(OUT, "heroes-and-events.md"),
        header("Heroes, Abilities and Events", "Use the hero name exactly as written (accents included, e.g. `Lúcio`, `Torbjörn`).", rev) + h,
    );

    // Per-hero lobby settings: the cheapest way to tune cooldowns, health,
    // damage etc. — no rules, no server load. Written under `settings > heroes`.
    const heroSettings = op.customGameSettingsSchema.heroes.values;
    const settingType = (v) => {
        if (v === "__percent__") return "percent (e.g. `80%`)";
        if (v === "__boolOnOff__" || v === "__boolReverseOnOff__") return "`On` / `Off`";
        if (v === "__int__") return "integer";
        if (v && typeof v === "object" && !Array.isArray(v)) {
            if (v.min !== undefined || v.max !== undefined) return `number ${v.min ?? ""}–${v.max ?? ""}`;
            const opts = Object.values(v).map(en).filter(Boolean);
            if (opts.length) return opts.map((o) => `\`${o}\``).join(" / ");
        }
        return typeof v === "string" ? v.replace(/__/g, "") : "";
    };
    const heroName = (k) => (k === "general" ? "General (all heroes)" : en(op.heroKw[k]) || k);
    let s =
        "Syntax (inside the top-level `settings { }` block):\n\n```\nheroes\n{\n\tGeneral\n\t{\n\t\tSymmetra\n\t\t{\n\t\t\tSentry Turret Cooldown Time: 80%\n\t\t\tHealth: 110%\n\t\t}\n\t}\n}\n```\n\n" +
        "`General` applies to both teams; use `Team 1` / `Team 2` to split. Settings directly under `General` (outside a hero block) apply to every hero.\n\n";
    const heroKeys = Object.keys(heroSettings)
        .filter((k) => heroSettings[k] && heroSettings[k].values)
        .sort((a, b) => (a === "general" ? -1 : b === "general" ? 1 : heroName(a).localeCompare(heroName(b))));
    for (const k of heroKeys) {
        s += `## ${heroName(k)}\n\n| Setting | Values |\n|---|---|\n`;
        for (const [, v] of Object.entries(heroSettings[k].values)) {
            if (!en(v)) continue;
            if (k !== "general" && v.include && !v.include.includes(k)) continue;
            if (k !== "general" && v.exclude && v.exclude.includes(k)) continue;
            s += `| ${en(v)} | ${settingType(v.values)} |\n`;
        }
        s += "\n";
    }
    fs.writeFileSync(
        path.join(OUT, "hero-settings.md"),
        header("Per-Hero Lobby Settings", "Exact setting names for `settings > heroes`. Prefer these over Workshop rules for flat stat/cooldown tweaks.", rev) + s,
    );

    console.log(`Wrote docs/api: ${actions.count} actions, ${values.count} values, ${enums.length} enums, ${Object.keys(op.heroKw).length} heroes.`);
})();
